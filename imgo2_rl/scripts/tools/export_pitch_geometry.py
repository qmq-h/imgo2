"""Export/check the standalone pitch controller's geometry from the canonical URDF.

Stdlib only. This is a generated kinematic table, not a second robot model.
"""
import argparse
import hashlib
import math
from pathlib import Path
import xml.etree.ElementTree as ET

REPO = Path(__file__).resolve().parents[3]
MODEL = REPO / "imgo2_description/urdf/imgo2_real.urdf"
OUTPUT = REPO / "imgo2_deploy/real/function/pitch_geometry_generated.h"


def vector(node, key, default="0 0 0"):
    return tuple(float(x) for x in node.get(key, default).split())


def generate():
    root = ET.parse(MODEL).getroot()
    rows = []
    for leg in ("FL", "FR", "RL", "RR"):
        names = [f"{leg}_{role}_joint" for role in ("hip", "thigh", "shank")] + [f"{leg}_Ankle"]
        joints = [root.find(f"joint[@name='{name}']") for name in names]
        assert all(j is not None for j in joints), names
        origins = [vector(j.find("origin"), "xyz") for j in joints]
        for j, axis in zip(joints[:3], ((1, 0, 0), (0, 1, 0), (0, 1, 0))):
            assert j.get("type") == "revolute" and vector(j.find("axis"), "xyz") == axis
            assert vector(j.find("origin"), "rpy") == (0, 0, 0), "IK requires unrotated joint origins"
        assert joints[0].find("parent").get("link") == "base"
        for parent, child in zip(joints, joints[1:]):
            assert parent.find("child").get("link") == child.find("parent").get("link")
        assert joints[3].get("type") == "fixed"
        assert origins[1][2] == 0 and origins[2][0] == 0
        assert origins[2][2] < 0 and origins[3][2] < 0
        spheres = [c for c in root.findall(f"link[@name='{leg}_FOOT']/collision")
                   if c.find("geometry/sphere") is not None]
        assert len(spheres) == 1, "IK anchors the physical foot sphere center"
        x, y, z = vector(spheres[0].find("origin"), "xyz")
        roll, pitch, yaw = vector(joints[3].find("origin"), "rpy")
        cr, sr, cp, sp, cy, sy = (math.cos(roll), math.sin(roll), math.cos(pitch),
                                math.sin(pitch), math.cos(yaw), math.sin(yaw))
        y, z = cr*y-sr*z, sr*y+cr*z
        x, z = cp*x+sp*z, -sp*x+cp*z
        x, y = cy*x-sy*y, sy*x+cy*y
        origins[3] = tuple(a+b for a, b in zip(origins[3], (x, y, z)))
        limits = [j.find("limit") for j in joints[:3]]
        lo = tuple(float(l.get("lower")) for l in limits)
        hi = tuple(float(l.get("upper")) for l in limits)
        fmt = lambda v: "{{" + ", ".join(format(x, ".12g") for x in v) + "}}"
        rows.append("    LegGeometry{" + ", ".join(fmt(v) for v in [*origins, lo, hi]) + "}")
    return ("// Generated by imgo2_rl/scripts/tools/export_pitch_geometry.py; DO NOT EDIT.\n"
            "// Source: imgo2_description/urdf/imgo2_real.urdf\n"
            f"// SHA256: {hashlib.sha256(MODEL.read_bytes()).hexdigest()}\n"
            "#pragma once\n#include <array>\nnamespace imgo2_pitch {\n"
            "using Vec3 = std::array<double,3>;\n"
            "struct LegGeometry { Vec3 hip, thigh, shank, foot, lower, upper; };\n"
            "inline constexpr std::array<LegGeometry,4> kLegs{{\n" + ",\n".join(rows) +
            "\n}};\n} // namespace imgo2_pitch\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("Pitch geometry is stale; run export_pitch_geometry.py")
        print("Pitch geometry matches canonical imgo2_real.urdf")
    else:
        OUTPUT.write_text(expected)
        print(OUTPUT.relative_to(REPO))


if __name__ == "__main__":
    main()
