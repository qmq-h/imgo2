def feet_height_body(
    env: ManagerBasedRLEnv,
    command_name: str,
    asset_cfg: SceneEntityCfg,
    target_height: float,
    tanh_mult: float,
    sensor_cfg: SceneEntityCfg = SceneEntityCfg("contact_forces", body_names=".*_FOOT"),
) -> torch.Tensor:
    """Swing-only body-frame foot-height cost, weighted by world horizontal foot speed.

    Use a negative reward weight. target_height is a body-frame z coordinate,
    not ground clearance. This term does not itself reward initiating a swing.
    The contact sensor must have track_air_time=True.
    """
    asset: RigidObject = env.scene[asset_cfg.name]
    contact_sensor: ContactSensor = env.scene.sensors[sensor_cfg.name]
    if not contact_sensor.cfg.track_air_time:
        raise ValueError("feet_height_body requires contact sensor track_air_time=True")

    # Resolve names once per entity/selection. ContactSensor.body_names reads
    # PhysX prim_paths; never query that property on every reward step.
    asset_ids = asset_cfg.body_ids
    sensor_ids = sensor_cfg.body_ids
    asset_key = ("slice", asset_ids.start, asset_ids.stop, asset_ids.step) if isinstance(asset_ids, slice) else tuple(asset_ids)
    sensor_key = ("slice", sensor_ids.start, sensor_ids.stop, sensor_ids.step) if isinstance(sensor_ids, slice) else tuple(sensor_ids)
    cache_key = (id(asset), id(contact_sensor), asset_key, sensor_key)
    cache = getattr(env, "_feet_height_body_index_cache", None)
    if cache is None:
        cache = env._feet_height_body_index_cache = {}
    if cache_key not in cache:
        asset_names = asset.body_names
        sensor_names = contact_sensor.body_names
        foot_names = (
            asset_names[asset_ids] if isinstance(asset_ids, slice)
            else [asset_names[i] for i in asset_ids]
        )
        selected_sensor_ids = (
            list(range(len(sensor_names)))[sensor_ids] if isinstance(sensor_ids, slice)
            else sensor_ids
        )
        sensor_id_by_name = {sensor_names[i]: i for i in selected_sensor_ids}
        missing = [name for name in foot_names if name not in sensor_id_by_name]
        if missing:
            raise ValueError(f"feet_height_body sensor is missing selected feet: {missing}")
        ordered_ids = [sensor_id_by_name[name] for name in foot_names]
        cache[cache_key] = (len(foot_names), ordered_ids)
    num_feet, ordered_sensor_ids = cache[cache_key]
    # Current air time avoids retaining the historical contact mask after lift-off.
    swing_mask = contact_sensor.data.current_air_time[:, ordered_sensor_ids] > 0.0

    relative_pos_w = asset.data.body_pos_w[:, asset_ids, :] - asset.data.root_pos_w.unsqueeze(1)
    root_quat = asset.data.root_quat_w.unsqueeze(1).expand(-1, num_feet, -1)
    foot_pos_b = math_utils.quat_apply_inverse(root_quat, relative_pos_w)
    height_error_sq = (foot_pos_b[:, :, 2] - target_height).square()
    # World velocity: do not subtract base translation or rotate into body axes.
    foot_speed_xy_w = asset.data.body_lin_vel_w[:, asset_ids, :2].norm(dim=-1)
    speed_weight = torch.tanh(tanh_mult * foot_speed_xy_w)
    reward = torch.sum(swing_mask * height_error_sq * speed_weight, dim=1)
    reward *= torch.linalg.norm(env.command_manager.get_command(command_name), dim=1) > 0.1
    reward *= torch.clamp(-asset.data.projected_gravity_b[:, 2], 0, 0.7) / 0.7
    return reward

